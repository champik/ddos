'use strict';
// Builds lightweight metadata for gen-review.js when the full metadata stage hasn't run yet.
// Usage: node scripts/build-review-metadata.js <projectDir>

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const { readJson, readJsonSafe, writeJsonAtomic } = require('./lib/state');
const { reconnectAfterSet, clipSequence, buildChapters } = require('./lib/timeline');

const projectDir = process.argv[2];
if (!projectDir) { console.error('Usage: node scripts/build-review-metadata.js <projectDir>'); process.exit(1); }

const plan      = readJson(path.join(projectDir, 'edit/episode-plan.json'));
const editorial = readJsonSafe(path.join(projectDir, 'edit/editorial.json'), {});
const scored    = readJson(path.join(projectDir, 'clips/scored-clips.json'));
const byId      = Object.fromEntries(scored.map(c => [c.id, c]));

const { fmt, buildVideoTags, buildShortsTags, buildDescriptionHashtags } = require('./lib/metadata-utils');

// ── helpers ───────────────────────────────────────────────────────────────────

function duration(clipId) {
  const sc = readJsonSafe(path.join(projectDir, 'processed', clipId, 'score.json'));
  if (sc?.trimmedDuration) return sc.trimmedDuration;
  const file = path.join(projectDir, 'processed', clipId, 'clean.mp4');
  if (!fs.existsSync(file)) return 0;
  const r = spawnSync('ffprobe', ['-v','quiet','-show_entries','format=duration','-of','csv=p=0', file], { encoding: 'utf8' });
  return parseFloat(r.stdout) || 0;
}

function reconnectDur() {
  const file = path.join(projectDir, 'edit/reconnecting.mp4');
  if (!fs.existsSync(file)) return 1.0;
  const r = spawnSync('ffprobe', ['-v','quiet','-show_entries','format=duration','-of','csv=p=0', file], { encoding: 'utf8' });
  return parseFloat(r.stdout) || 1.0;
}

const ALL_CLIP_IDS = editorial.clipOrder ? clipSequence(editorial) : plan.groups.flatMap(g => g.clipIds);

// ── chapters (reconnect-позиції з editorial.json — як у фінальному відео) ───────

const chapters = buildChapters({
  clipIds: ALL_CLIP_IDS,
  reconnectAfter: reconnectAfterSet(editorial),
  getDur: duration,
  getStreamer: id => byId[id]?.broadcaster_name || '?',
  introDur: 1.25,
  reconnectDur: reconnectDur(),
});

const chaptersStr = chapters.map(c => fmt(c.t) + ' ' + c.label).join('\n');

// ── tags + hashtags ───────────────────────────────────────────────────────────

const tags = buildVideoTags(ALL_CLIP_IDS, byId);
const hashtagStr = buildDescriptionHashtags(ALL_CLIP_IDS, byId);

// ── shorts ────────────────────────────────────────────────────────────────────

const shortsMetadata = (plan.shortClipIds || []).map(clipId => {
  const c = byId[clipId] || {};
  const name = c.broadcaster_name || 'Streamer';
  return {
    clipId,
    title: `${name} Had A Moment | Daily Dose Of Stream`,
    description: '',
    ...buildShortsTags(clipId, byId),
  };
});

// ── write ─────────────────────────────────────────────────────────────────────

const metadata = {
  titleOptions: ['[Generated by Claude during METADATA stage]'],
  description: 'Your daily dose of the best Twitch moments.\n\n' + chaptersStr + '\n\n' + hashtagStr,
  tags,
  thumbnailText: '',
  shortsMetadata,
};

fs.mkdirSync(path.join(projectDir, 'exports'), { recursive: true });
writeJsonAtomic(path.join(projectDir, 'exports', 'metadata.json'), metadata);
console.log('[OK] review metadata.json written');
console.log(`Tags (${tags.length}): ${tags.join(', ')}`);
